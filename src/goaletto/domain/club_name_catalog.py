ENGLISH_CLUB_NAMES = tuple(f"{place} {suffix}" for place in PLACES for suffix in SUFFIXES)


def name_key(value: str) -> str:
    """Compare actual displayed names, including legacy Cyrillic projections."""
    return " ".join(latin_name(value).casefold().split())


def allocate_names(count: int, *, seed: str, existing: Iterable[str] = ()) -> tuple[str, ...]:
    """Use every unused name before reusing the least common ones at exhaustion."""
    if type(count) is not int or count < 0:
        raise ValueError("Name count must be a nonnegative integer")
    usage = Counter(name_key(name) for name in existing)
    queue = [
        (
            usage[name_key(name)],
            sha256(f"{CLUB_NAMING_POLICY}:{seed}:{name}".encode()).digest(),
            name,
        )
        for name in ENGLISH_CLUB_NAMES
    ]
    heapify(queue)
    result = []
    used_in_batch: list[tuple[int, bytes, str]] = []
    for _ in range(count):
        if not queue:
            queue, used_in_batch = used_in_batch, []
            heapify(queue)
        used, order, name = heappop(queue)
        result.append(name)
        used_in_batch.append((used + 1, order, name))
    return tuple(result)
